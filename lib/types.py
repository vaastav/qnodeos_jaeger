class SingleQubitState(Enum):
    """Definition of some common states."""

    PLUS_Z = ket("0")
    MINUS_Z = ket("1")
    PLUS_X = (ket("0") + ket("1")).unit()
    MINUS_X = (ket("0") - ket("1")).unit()
    PLUS_Y = (ket("0") + 1j * ket("1")).unit()
    MINUS_Y = (ket("0") - 1j * ket("1")).unit()


class BellState(Enum):
    """Enumeration of all possible Bell states."""

    PhiPlus = auto()
    PhiMinus = auto()
    PsiPlus = auto()
    PsiMinus = auto()
