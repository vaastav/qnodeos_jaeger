    NOP = 0
    INI = 1
    MSR = 4
    ENT = 5
    ENM = 6
    PMG = 7
    # SQGates ("M" prefix stands for "minus")
    X90 = 8 << 4 | 2
    X180 = 16 << 4 | 2
    MX90 = 24 << 4 | 2
    Y90 = 40 << 4 | 2
    Y180 = 48 << 4 | 2
    MY90 = 56 << 4 | 2


